/**
 * 故人情報の自由記入欄に現れる語から、関連するテーマ文例を選ぶ。
 * プロンプトが肥大しないよう最大 limit 件まで。該当が無ければ空配列。
 */
export function selectThemeExamples(haystack: string, limit = 4): ThemeExample[] {
  if (!haystack.trim()) return [];
  const scored = THEME_EXAMPLES.map((t) => ({
    theme: t,
    score: t.keywords.reduce((n, k) => (haystack.includes(k) ? n + 1 : n), 0),
  }))
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.theme);
}

/** 月に対応する季節フレーズ（原文）を返す。 */
export function seasonalPhrasesFor(month: number | null): SeasonalPhrase[] {
  if (month === null) return [];
  return SEASONAL_PHRASES_BY_MONTH[month] ?? [];
}
